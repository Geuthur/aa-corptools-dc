class SocketAccessError(Exception):
    """Error raised when a test script accesses the network"""


class NoSocketsTestCase(TestCase):
    """Variation of Django's TestCase class that prevents any network use.

    Example:

        .. code-block:: python

            class TestMyStuff(BaseTestCase):
                def test_should_do_what_i_need(self): ...

    """

    @classmethod
    def setUpClass(cls):
        cls.socket_original = socket.socket
        socket.socket = cls.guard
        return super().setUpClass()

    @classmethod
    def tearDownClass(cls):
        socket.socket = cls.socket_original
        return super().tearDownClass()

    @staticmethod
    def guard(*args, **kwargs):
        raise SocketAccessError("Attempted to access network")


class DoctrineCheckerTestCase(NoSocketsTestCase):
    """
    Preloaded Testcase class for Corp Tools Doctrine tests without Network access.

    Pre-Load:
        * Alliance Auth Characters, Corporation, Alliance Data (generated by factories)

    Available Request Factory:
        `self.factory`

    Available corporations:
        * `corp` Corporation of `user`, `manage_own_user` and `manage_user`.
            * Member of `alliance`
        * `corp2` Corporation of `no_access`.
            * Member of `alliance`
        * `corp3` Corporation of `superuser`.
            * Without alliance

    Available test users (each has a main character in `<name>_character`):
        * `user` User with standard Corp Tools Doctrine access.
            * 'corptools_doctrine.basic_access' Permission
            * Corporation `corp`
        * `no_access` User without any permission.
            * Corporation `corp2`
        * `superuser` Superuser.
            * Access to whole Application
            * Corporation `corp3`
        * `manage_own_user` User with manage own corporation access.
            * 'corptools_doctrine.basic_access' Permission
            * 'corptools_doctrine.corp_access' Permission
            * 'corptools_doctrine.alliance_access' Permission
            * 'corptools_doctrine.manage_access' Permission
            * Corporation `corp`
        * `manage_user` User with manage corporations access.
            * 'corptools_doctrine.basic_access' Permission
            * 'corptools_doctrine.corp_access' Permission
            * 'corptools_doctrine.alliance_access' Permission
            * 'corptools_doctrine.manage_access' Permission
            * 'corptools_doctrine.admin_access' Permission
            * Corporation `corp`

    Example:
        .. code-block:: python

            class TestMyDoctrineStuff(DoctrineCheckerTestCase):
                def test_should_do_what_i_need(self):
                    user = self.user
    """

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        # Corporations and Alliance
        cls.alliance = EveAllianceInfoFactory()
        cls.corp = EveCorporationInfoFactory(alliance=cls.alliance)
        cls.corp2 = EveCorporationInfoFactory(alliance=cls.alliance)
        cls.corp3 = EveCorporationInfoFactory(create_alliance=False)

        # Request Factory
        cls.factory = RequestFactory()

        # User with Standard Access - Corporation 1
        cls.user = UserMainFactory(
            main_character__character=EveCharacterFactory(corporation=cls.corp)
        )
        cls.user_character = cls.user.profile.main_character
        cls.useraudit = create_owner_from_user(user=cls.user)
        # User without Access - Corporation 2
        cls.no_access = UserMainFactory(
            permissions=[],
            main_character__character=EveCharacterFactory(corporation=cls.corp2),
        )
        cls.no_access_character = cls.no_access.profile.main_character
        cls.no_accessaudit = create_owner_from_user(user=cls.no_access)
        # User with Superuser Access - Corporation 3
        cls.superuser = UserMainFactory(
            permissions=[],
            main_character__character=EveCharacterFactory(corporation=cls.corp3),
        )
        cls.superuser.is_superuser = True
        cls.superuser.save()
        cls.superuser_character = cls.superuser.profile.main_character
        cls.superuseraudit = create_owner_from_user(user=cls.superuser)
        # User with Manage Own Corporation Access - Corporation 1
        cls.manage_own_user = UserMainFactory(
            permissions=[
                "corptools_doctrine.basic_access",
                "corptools_doctrine.corp_access",
                "corptools_doctrine.alliance_access",
                "corptools_doctrine.manage_access",
            ],
            main_character__character=EveCharacterFactory(corporation=cls.corp),
        )
        cls.manage_own_character = cls.manage_own_user.profile.main_character
        cls.manage_own_audit = create_owner_from_user(user=cls.manage_own_user)
        # User with Manage Alliance - Corporation 1
        cls.manage_user = UserMainFactory(
            permissions=[
                "corptools_doctrine.basic_access",
                "corptools_doctrine.corp_access",
                "corptools_doctrine.alliance_access",
                "corptools_doctrine.manage_access",
                "corptools_doctrine.admin_access",
            ],
            main_character__character=EveCharacterFactory(corporation=cls.corp),
        )
        cls.manage_character = cls.manage_user.profile.main_character
        cls.manage_audit = create_owner_from_user(user=cls.manage_user)

        cls.category = create_evecategory(
            category_id=16,
            name="Skill",
        )

        cls.group = create_evegroup(
            group_id=257,
            name="Spaceship Command",
            category=cls.category,
        )

        cls.evetype = create_eveitemtype(
            type_id=17940,
            name="Mining Barge",
            published=True,
            group=cls.group,
        )

        cls.item_type = ItemTypeFactory(
            id=17940,
            name="Mining Barge",
            group__id=257,
            group__name="Spaceship Command",
            group__category__id=16,
            group__category__name="Skill",
        )

    def _middleware_process_request(self, request: WSGIRequest):
        """Helper method to process middleware for a request."""
        session_middleware = SessionMiddleware(Mock())
        session_middleware.process_request(request)
        message_middleware = MessageMiddleware(Mock())
        message_middleware.process_request(request)
